
-- 01_esquema.sql
-- Proceso: cobro del evento. Se ejecuta sobre una base vacía (sin DROP).
-- Tipos, nombres y divergencias: ver README.

-- ---------- Tablas de soporte (las exigen las FK obligatorias) ----------

CREATE TABLE persona (
    id_persona       INTEGER GENERATED BY DEFAULT AS IDENTITY,
    identificacion   VARCHAR(30)  NOT NULL,
    nombre_completo  VARCHAR(120) NOT NULL,
    CONSTRAINT pk_persona PRIMARY KEY (id_persona),
    CONSTRAINT uq_persona_identificacion UNIQUE (identificacion)
);

-- CLIENTE: persona u organización, nunca ambas (RN-05, arco exclusivo)
CREATE TABLE cliente (
    id_cliente               INTEGER GENERATED BY DEFAULT AS IDENTITY,
    tipo_cliente             VARCHAR(15)  NOT NULL,
    id_persona               INTEGER,
    identificacion_juridica  VARCHAR(30),
    razon_social             VARCHAR(150),
    CONSTRAINT pk_cliente PRIMARY KEY (id_cliente),
    CONSTRAINT fk_cliente_persona FOREIGN KEY (id_persona)
        REFERENCES persona (id_persona),
    CONSTRAINT uq_cliente_id_persona UNIQUE (id_persona),
    CONSTRAINT uq_cliente_identificacion_juridica UNIQUE (identificacion_juridica),
    CONSTRAINT ck_cliente_tipo CHECK (tipo_cliente IN ('Persona', 'Organización')),
    CONSTRAINT ck_cliente_arco_exclusivo CHECK (
        (tipo_cliente = 'Persona'
            AND id_persona IS NOT NULL
            AND identificacion_juridica IS NULL
            AND razon_social IS NULL)
     OR (tipo_cliente = 'Organización'
            AND id_persona IS NULL
            AND identificacion_juridica IS NOT NULL
            AND razon_social IS NOT NULL)
    )
);

-- ESPACIO: espacio propio o de terceros (RN-01)
CREATE TABLE espacio (
    id_espacio           INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nombre               VARCHAR(100) NOT NULL,
    tipo_propiedad       VARCHAR(15)  NOT NULL,
    ubicacion            VARCHAR(150) NOT NULL,
    capacidad            INTEGER      NOT NULL,
    propietario_externo  VARCHAR(150),
    divisible            BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT pk_espacio PRIMARY KEY (id_espacio),
    CONSTRAINT ck_espacio_tipo_propiedad CHECK (tipo_propiedad IN ('Propio', 'De terceros')),
    CONSTRAINT ck_espacio_capacidad CHECK (capacidad > 0),
    CONSTRAINT ck_espacio_propietario CHECK (
        (tipo_propiedad = 'De terceros') = (propietario_externo IS NOT NULL)
    )
);

CREATE TABLE solicitud (
    id_solicitud           INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_cliente             INTEGER      NOT NULL,
    fecha_solicitud        DATE         NOT NULL,
    tipo_evento            VARCHAR(40)  NOT NULL,
    fecha_desde            DATE         NOT NULL,
    fecha_hasta            DATE         NOT NULL,
    horario_aproximado     VARCHAR(40)  NOT NULL,
    asistentes_esperados   INTEGER      NOT NULL,
    ubicacion_preferida    VARCHAR(150),
    necesidades_conocidas  TEXT,
    estado_solicitud       VARCHAR(15)  NOT NULL DEFAULT 'En evaluación',
    CONSTRAINT pk_solicitud PRIMARY KEY (id_solicitud),
    CONSTRAINT fk_solicitud_cliente FOREIGN KEY (id_cliente)
        REFERENCES cliente (id_cliente),
    CONSTRAINT ck_solicitud_rango CHECK (fecha_hasta >= fecha_desde),
    CONSTRAINT ck_solicitud_asistentes CHECK (asistentes_esperados > 0),
    CONSTRAINT ck_solicitud_estado CHECK (
        estado_solicitud IN ('En evaluación', 'Aprobada', 'Descartada'))
);

-- Sin id_area: FK opcional a AREA, fuera de alcance (README, D4)
CREATE TABLE alternativa_solicitud (
    id_alternativa      INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_solicitud        INTEGER     NOT NULL,
    fecha_desde         DATE        NOT NULL,
    fecha_hasta         DATE        NOT NULL,
    id_espacio          INTEGER     NOT NULL,
    estado_alternativa  VARCHAR(15) NOT NULL DEFAULT 'En evaluación',
    CONSTRAINT pk_alternativa_solicitud PRIMARY KEY (id_alternativa),
    CONSTRAINT fk_alternativa_solicitud_solicitud FOREIGN KEY (id_solicitud)
        REFERENCES solicitud (id_solicitud),
    CONSTRAINT fk_alternativa_solicitud_espacio FOREIGN KEY (id_espacio)
        REFERENCES espacio (id_espacio),
    CONSTRAINT ck_alternativa_solicitud_rango CHECK (fecha_hasta >= fecha_desde),
    CONSTRAINT ck_alternativa_solicitud_estado CHECK (
        estado_alternativa IN ('En evaluación', 'Descartada'))
);

CREATE TABLE propuesta (
    id_propuesta      INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_solicitud      INTEGER     NOT NULL,
    numero_version    INTEGER     NOT NULL,
    fecha_version     DATE        NOT NULL,
    vigencia_hasta    DATE        NOT NULL,
    condiciones       TEXT        NOT NULL,
    estado_propuesta  VARCHAR(15) NOT NULL DEFAULT 'Vigente',
    CONSTRAINT pk_propuesta PRIMARY KEY (id_propuesta),
    CONSTRAINT fk_propuesta_solicitud FOREIGN KEY (id_solicitud)
        REFERENCES solicitud (id_solicitud),
    CONSTRAINT uq_propuesta_solicitud_version UNIQUE (id_solicitud, numero_version),
    CONSTRAINT ck_propuesta_version CHECK (numero_version > 0),
    CONSTRAINT ck_propuesta_vigencia CHECK (vigencia_hasta >= fecha_version),
    CONSTRAINT ck_propuesta_estado CHECK (
        estado_propuesta IN ('Vigente', 'Superada', 'Rechazada'))
);


-- ---------- Núcleo del proceso de cobro ----------

-- EVENTO: incluye la confirmación (A-06)
CREATE TABLE evento (
    id_evento                 INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_propuesta              INTEGER       NOT NULL,
    id_alternativa            INTEGER       NOT NULL,
    id_persona_autorizada     INTEGER       NOT NULL,
    fecha_aceptacion          DATE          NOT NULL,
    monto_adelanto_requerido  NUMERIC(12,2) NOT NULL,
    tipo_evento               VARCHAR(40)   NOT NULL,
    fecha_inicio              DATE          NOT NULL,
    fecha_fin                 DATE          NOT NULL,
    estado_evento             VARCHAR(15)   NOT NULL DEFAULT 'Confirmado',
    fecha_cierre              DATE,
    CONSTRAINT pk_evento PRIMARY KEY (id_evento),
    CONSTRAINT fk_evento_propuesta FOREIGN KEY (id_propuesta)
        REFERENCES propuesta (id_propuesta),
    CONSTRAINT fk_evento_alternativa FOREIGN KEY (id_alternativa)
        REFERENCES alternativa_solicitud (id_alternativa),
    CONSTRAINT fk_evento_persona_autorizada FOREIGN KEY (id_persona_autorizada)
        REFERENCES persona (id_persona),
    -- 1:1 mediante FK única
    CONSTRAINT uq_evento_propuesta UNIQUE (id_propuesta),
    CONSTRAINT uq_evento_alternativa UNIQUE (id_alternativa),
    CONSTRAINT ck_evento_adelanto CHECK (monto_adelanto_requerido >= 0),
    CONSTRAINT ck_evento_fechas CHECK (fecha_fin >= fecha_inicio),
    CONSTRAINT ck_evento_estado CHECK (
        estado_evento IN ('Confirmado', 'En ejecución', 'Cerrado', 'Cancelado')),
    CONSTRAINT ck_evento_cierre CHECK (
        estado_evento <> 'Cerrado' OR fecha_cierre IS NOT NULL)
);

CREATE TABLE servicio (
    id_servicio      INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nombre           VARCHAR(100) NOT NULL,
    categoria        VARCHAR(40)  NOT NULL,
    modo_suministro  VARCHAR(10)  NOT NULL,
    CONSTRAINT pk_servicio PRIMARY KEY (id_servicio),
    CONSTRAINT ck_servicio_modo CHECK (modo_suministro IN ('Propio', 'Externo'))
);

-- Sin id_propuesta, numero_linea ni id_actividad: FK opcionales fuera de alcance (D4)
CREATE TABLE servicio_evento (
    id_servicio_evento      INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_evento               INTEGER       NOT NULL,
    id_servicio             INTEGER       NOT NULL,
    alcance                 VARCHAR(200)  NOT NULL,
    cantidad                INTEGER       NOT NULL,
    inicio_servicio         TIMESTAMP     NOT NULL,
    fin_servicio            TIMESTAMP     NOT NULL,
    precio_acordado         NUMERIC(12,2) NOT NULL,
    situacion_contratacion  VARCHAR(15)   NOT NULL,
    estado_prestacion       VARCHAR(25)   NOT NULL DEFAULT 'Por verificar',
    cantidad_prestada       INTEGER,
    observacion_prestacion  TEXT,
    CONSTRAINT pk_servicio_evento PRIMARY KEY (id_servicio_evento),
    CONSTRAINT fk_servicio_evento_evento FOREIGN KEY (id_evento)
        REFERENCES evento (id_evento),
    CONSTRAINT fk_servicio_evento_servicio FOREIGN KEY (id_servicio)
        REFERENCES servicio (id_servicio),
    -- Destino de la FK compuesta desde CARGO (D3)
    CONSTRAINT uq_servicio_evento_id_evento UNIQUE (id_servicio_evento, id_evento),
    CONSTRAINT ck_servicio_evento_cantidad CHECK (cantidad > 0),
    CONSTRAINT ck_servicio_evento_horario CHECK (inicio_servicio < fin_servicio),
    CONSTRAINT ck_servicio_evento_precio CHECK (precio_acordado >= 0),
    CONSTRAINT ck_servicio_evento_situacion CHECK (
        situacion_contratacion IN ('Propio', 'Por contratar', 'Contratado', 'Cancelado')),
    CONSTRAINT ck_servicio_evento_prestacion CHECK (
        estado_prestacion IN ('Por verificar', 'Prestado',
                              'Prestado parcialmente', 'No prestado')),
    -- RN-17: cantidad_prestada solo si fue parcial
    CONSTRAINT ck_servicio_evento_parcial CHECK (
        ((estado_prestacion = 'Prestado parcialmente') = (cantidad_prestada IS NOT NULL))
        AND (cantidad_prestada IS NULL
             OR (cantidad_prestada > 0 AND cantidad_prestada < cantidad))
    )
);

-- Sin id_ajuste ni id_incidencia (D4): solo cargos Componente y Penalización
CREATE TABLE cargo (
    id_cargo                INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_evento               INTEGER       NOT NULL,
    tipo_cargo              VARCHAR(15)   NOT NULL,
    descripcion             VARCHAR(200)  NOT NULL,
    monto                   NUMERIC(12,2) NOT NULL,
    fecha_cargo             DATE          NOT NULL,
    id_servicio_evento      INTEGER,
    justificacion           TEXT,
    id_cliente_responsable  INTEGER       NOT NULL,
    estado_cargo            VARCHAR(25)   NOT NULL DEFAULT 'Pendiente de aprobación',
    id_persona_aprueba      INTEGER,
    fecha_aprobacion        DATE,
    CONSTRAINT pk_cargo PRIMARY KEY (id_cargo),
    CONSTRAINT fk_cargo_evento FOREIGN KEY (id_evento)
        REFERENCES evento (id_evento),
    -- El servicio cobrado debe ser del mismo evento (D2)
    CONSTRAINT fk_cargo_servicio_evento FOREIGN KEY (id_servicio_evento, id_evento)
        REFERENCES servicio_evento (id_servicio_evento, id_evento),
    CONSTRAINT fk_cargo_cliente_responsable FOREIGN KEY (id_cliente_responsable)
        REFERENCES cliente (id_cliente),
    CONSTRAINT fk_cargo_persona_aprueba FOREIGN KEY (id_persona_aprueba)
        REFERENCES persona (id_persona),
    -- Destino de la FK compuesta desde APLICACION_PAGO (D3)
    CONSTRAINT uq_cargo_id_evento UNIQUE (id_cargo, id_evento),
    CONSTRAINT ck_cargo_tipo CHECK (
        tipo_cargo IN ('Componente', 'Ajuste', 'Adicional', 'Penalización')),
    CONSTRAINT ck_cargo_monto CHECK (monto > 0),
    CONSTRAINT ck_cargo_estado CHECK (
        estado_cargo IN ('Pendiente de aprobación', 'Aprobado', 'Rechazado', 'Anulado')),
    -- RN-18: cada tipo exige su origen; la penalización, justificación
    CONSTRAINT ck_cargo_origen CHECK (
        (tipo_cargo = 'Componente'
            AND id_servicio_evento IS NOT NULL AND justificacion IS NULL)
     OR (tipo_cargo = 'Penalización'
            AND id_servicio_evento IS NULL AND justificacion IS NOT NULL)
    ),
    CONSTRAINT ck_cargo_aprobacion CHECK (
        (id_persona_aprueba IS NULL) = (fecha_aprobacion IS NULL))
);

CREATE TABLE pago (
    id_pago      INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_evento    INTEGER       NOT NULL,
    fecha_pago   DATE          NOT NULL DEFAULT CURRENT_DATE,
    monto        NUMERIC(12,2) NOT NULL,
    medio_pago   VARCHAR(15)   NOT NULL,
    referencia   VARCHAR(40),
    es_adelanto  BOOLEAN       NOT NULL DEFAULT FALSE,
    CONSTRAINT pk_pago PRIMARY KEY (id_pago),
    CONSTRAINT fk_pago_evento FOREIGN KEY (id_evento)
        REFERENCES evento (id_evento),
    -- Destino de la FK compuesta desde APLICACION_PAGO (D3)
    CONSTRAINT uq_pago_id_evento UNIQUE (id_pago, id_evento),
    -- Los NULL no chocan: varios pagos en efectivo sin referencia son válidos
    CONSTRAINT uq_pago_medio_referencia UNIQUE (medio_pago, referencia),
    CONSTRAINT ck_pago_monto CHECK (monto > 0),
    CONSTRAINT ck_pago_medio CHECK (
        medio_pago IN ('Efectivo', 'Transferencia', 'SINPE Móvil', 'Tarjeta', 'Cheque')),
    CONSTRAINT ck_pago_referencia CHECK (
        medio_pago = 'Efectivo' OR referencia IS NOT NULL)
);

-- Asociativa N:M. id_evento agregado: pago y cargo del mismo evento (D1)
CREATE TABLE aplicacion_pago (
    id_pago         INTEGER       NOT NULL,
    id_cargo        INTEGER       NOT NULL,
    id_evento       INTEGER       NOT NULL,
    monto_aplicado  NUMERIC(12,2) NOT NULL,
    CONSTRAINT pk_aplicacion_pago PRIMARY KEY (id_pago, id_cargo),
    CONSTRAINT fk_aplicacion_pago_pago FOREIGN KEY (id_pago, id_evento)
        REFERENCES pago (id_pago, id_evento),
    CONSTRAINT fk_aplicacion_pago_cargo FOREIGN KEY (id_cargo, id_evento)
        REFERENCES cargo (id_cargo, id_evento),
    CONSTRAINT ck_aplicacion_pago_monto CHECK (monto_aplicado > 0)
);


-- ---------- Índices (PostgreSQL no indexa las FK) ----------

-- El saldo y Q1–Q3 filtran cargos por evento
CREATE INDEX idx_cargo_id_evento ON cargo (id_evento);

-- El saldo suma los pagos de un evento
CREATE INDEX idx_pago_id_evento ON pago (id_evento);

-- La PK empieza por id_pago y no sirve para buscar por cargo
CREATE INDEX idx_aplicacion_pago_id_cargo ON aplicacion_pago (id_cargo);
