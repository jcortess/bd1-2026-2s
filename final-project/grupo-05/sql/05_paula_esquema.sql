\set ON_ERROR_STOP on
BEGIN;
SET LOCAL search_path = huellas, pg_catalog;

-- P-01 a P-06: nueve relaciones originales y una ampliación de RN-19.
-- Instalar después de 01–04. No redefine ninguna tabla de los compañeros.
CREATE DOMAIN estado_solicitud AS text CHECK (VALUE IN
    ('RECIBIDA','EN_EVALUACION','PENDIENTE_INFORMACION','APROBADA','RECHAZADA','CANCELADA','VENCIDA'));

CREATE TABLE reporte (
    id_reporte bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id_reporte > 0),
    reportante_id bigint REFERENCES persona,
    fecha_reporte instante,
    lugar_aproximado texto_no_vacio,
    situacion_observada texto_no_vacio
);
CREATE TABLE reporte_animal (
    reporte_id bigint NOT NULL REFERENCES reporte,
    animal_codigo texto_no_vacio NOT NULL REFERENCES animal,
    PRIMARY KEY (reporte_id, animal_codigo)
);

-- Se conservan el discriminador, la PK compuesta y los campos condicionales de Lab03.
CREATE TABLE evaluacion_salud (
    id_evaluacion bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id_evaluacion > 0),
    animal_codigo texto_no_vacio NOT NULL,
    ingreso_id bigint NOT NULL,
    tipo_evaluacion text NOT NULL CHECK (tipo_evaluacion IN ('INICIAL','REVISION_VETERINARIA')),
    fecha_evaluacion instante NOT NULL,
    veterinario_id bigint REFERENCES persona,
    registro_veterinario_id bigint REFERENCES participacion,
    motivo texto_no_vacio,
    observaciones texto_no_vacio,
    peso numeric(7,3) CHECK (peso > 0 AND peso < 'Infinity'::numeric),
    recomendaciones texto_no_vacio,
    CONSTRAINT evaluacion_ingreso_animal_fk FOREIGN KEY (ingreso_id, animal_codigo)
        REFERENCES ingreso(id_ingreso, animal_codigo),
    CONSTRAINT uq_evaluacion_id_tipo UNIQUE (id_evaluacion, tipo_evaluacion),
    CONSTRAINT evaluacion_registro_par CHECK ((veterinario_id IS NULL) = (registro_veterinario_id IS NULL)),
    CONSTRAINT chk_revision_campos CHECK (tipo_evaluacion <> 'REVISION_VETERINARIA' OR
        (veterinario_id IS NOT NULL AND registro_veterinario_id IS NOT NULL AND motivo IS NOT NULL
         AND observaciones IS NOT NULL AND peso IS NOT NULL AND recomendaciones IS NOT NULL))
);
CREATE UNIQUE INDEX evaluacion_inicial_etapa_uq ON evaluacion_salud(ingreso_id)
    WHERE tipo_evaluacion = 'INICIAL';
CREATE INDEX evaluacion_animal_fecha_idx ON evaluacion_salud(animal_codigo, fecha_evaluacion);
CREATE INDEX evaluacion_registro_idx ON evaluacion_salud(registro_veterinario_id);

CREATE TABLE diagnostico (
    id_diagnostico bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id_diagnostico > 0),
    nombre_estandarizado texto_no_vacio NOT NULL UNIQUE
        CHECK (nombre_estandarizado = btrim(nombre_estandarizado))
);
CREATE TABLE diagnostico_revision (
    evaluacion_id bigint NOT NULL,
    tipo_evaluacion text NOT NULL DEFAULT 'REVISION_VETERINARIA'
        CHECK (tipo_evaluacion = 'REVISION_VETERINARIA'),
    diagnostico_id bigint NOT NULL REFERENCES diagnostico,
    estado_diagnostico text NOT NULL CHECK (estado_diagnostico IN ('PROVISIONAL','CONFIRMADO','DESCARTADO')),
    PRIMARY KEY (evaluacion_id, diagnostico_id),
    CONSTRAINT fk_diagnostico_revision_evaluacion FOREIGN KEY (evaluacion_id, tipo_evaluacion)
        REFERENCES evaluacion_salud(id_evaluacion, tipo_evaluacion)
);

CREATE TABLE cambio_disponibilidad (
    id_cambio bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id_cambio > 0),
    animal_codigo texto_no_vacio NOT NULL,
    ingreso_id bigint NOT NULL,
    fecha instante NOT NULL,
    estado_disponibilidad text NOT NULL CHECK (estado_disponibilidad IN ('HABILITADO','NO_DISPONIBLE')),
    responsable_id bigint NOT NULL REFERENCES persona,
    participacion_responsable_id bigint NOT NULL REFERENCES participacion,
    observacion_general texto_no_vacio NOT NULL,
    valoracion_sanitaria texto_no_vacio NOT NULL,
    CONSTRAINT disponibilidad_ingreso_animal_fk FOREIGN KEY (ingreso_id, animal_codigo)
        REFERENCES ingreso(id_ingreso, animal_codigo)
);
CREATE INDEX disponibilidad_contexto_fecha_idx ON cambio_disponibilidad(animal_codigo, ingreso_id, fecha DESC, id_cambio DESC);

CREATE TABLE solicitud_adopcion (
    id_solicitud bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id_solicitud > 0),
    clave_operacion uuid NOT NULL UNIQUE,
    solicitante_id bigint NOT NULL REFERENCES persona,
    fecha_solicitud instante NOT NULL,
    informacion_vivienda texto_no_vacio NOT NULL,
    integrantes_hogar texto_no_vacio NOT NULL,
    experiencia_animales texto_no_vacio NOT NULL,
    condiciones_cuidado texto_no_vacio NOT NULL
);
CREATE INDEX solicitud_persona_fecha_idx ON solicitud_adopcion(solicitante_id, fecha_solicitud);
CREATE TABLE solicitud_animal (
    solicitud_id bigint NOT NULL REFERENCES solicitud_adopcion,
    animal_codigo texto_no_vacio NOT NULL REFERENCES animal,
    fecha_interes instante NOT NULL,
    PRIMARY KEY (solicitud_id, animal_codigo)
);

CREATE TABLE evento_solicitud (
    id_evento_solicitud bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id_evento_solicitud > 0),
    clave_operacion uuid NOT NULL UNIQUE,
    solicitud_id bigint NOT NULL REFERENCES solicitud_adopcion,
    fecha instante NOT NULL,
    tipo_evento text NOT NULL CHECK (tipo_evento IN
        ('RECEPCION','ENTREVISTA','VISITA_HOGAR','INFORMACION','OTRA_ACTIVIDAD','DECISION')),
    responsable_id bigint NOT NULL REFERENCES persona,
    participacion_responsable_id bigint NOT NULL REFERENCES participacion,
    resultado_actividad texto_no_vacio,
    estado_resultante estado_solicitud,
    observaciones texto_no_vacio,
    razon texto_no_vacio,
    antecedente_decision_id bigint,
    CONSTRAINT evento_contexto_uq UNIQUE (id_evento_solicitud, solicitud_id),
    CONSTRAINT evento_antecedente_fk FOREIGN KEY (antecedente_decision_id, solicitud_id)
        REFERENCES evento_solicitud(id_evento_solicitud, solicitud_id),
    CONSTRAINT evento_contenido CHECK (
        (tipo_evento IN ('RECEPCION','DECISION') AND estado_resultante IS NOT NULL AND razon IS NOT NULL
         AND resultado_actividad IS NULL)
        OR (tipo_evento NOT IN ('RECEPCION','DECISION') AND resultado_actividad IS NOT NULL
            AND observaciones IS NOT NULL AND estado_resultante IS NULL AND razon IS NULL
            AND antecedente_decision_id IS NULL)
    ),
    CONSTRAINT evento_recepcion CHECK (tipo_evento <> 'RECEPCION' OR
        (estado_resultante = 'RECIBIDA' AND antecedente_decision_id IS NULL))
);
CREATE UNIQUE INDEX evento_una_recepcion_uq ON evento_solicitud(solicitud_id) WHERE tipo_evento = 'RECEPCION';
CREATE INDEX evento_historia_idx ON evento_solicitud(solicitud_id, fecha, id_evento_solicitud);

-- El hogar concreto es la instantánea inmutable de los cuatro datos de SOLICITUD_ADOPCION.
-- Una reevaluación añade otra fila; nunca convierte el interés en un resultado.
CREATE TABLE compatibilidad_animal_hogar (
    id_compatibilidad bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id_compatibilidad > 0),
    clave_operacion uuid NOT NULL UNIQUE,
    solicitud_id bigint NOT NULL,
    animal_codigo texto_no_vacio NOT NULL,
    ingreso_id bigint NOT NULL,
    fecha instante NOT NULL,
    responsable_id bigint NOT NULL REFERENCES persona,
    participacion_responsable_id bigint NOT NULL REFERENCES participacion,
    resultado text NOT NULL CHECK (resultado IN ('FAVORABLE','NO_FAVORABLE','PENDIENTE_INFORMACION')),
    valoracion_hogar texto_no_vacio NOT NULL,
    razon texto_no_vacio NOT NULL,
    observaciones texto_no_vacio NOT NULL,
    actividad_contexto_id bigint,
    CONSTRAINT compatibilidad_interes_fk FOREIGN KEY (solicitud_id, animal_codigo)
        REFERENCES solicitud_animal(solicitud_id, animal_codigo),
    CONSTRAINT compatibilidad_ingreso_fk FOREIGN KEY (ingreso_id, animal_codigo)
        REFERENCES ingreso(id_ingreso, animal_codigo),
    CONSTRAINT compatibilidad_actividad_fk FOREIGN KEY (actividad_contexto_id, solicitud_id)
        REFERENCES evento_solicitud(id_evento_solicitud, solicitud_id),
    CONSTRAINT compatibilidad_contexto_uq UNIQUE (id_compatibilidad, solicitud_id, animal_codigo, ingreso_id)
);
CREATE INDEX compatibilidad_vigente_idx ON compatibilidad_animal_hogar
    (solicitud_id, animal_codigo, ingreso_id, fecha DESC, id_compatibilidad DESC);
CREATE INDEX reporte_animal_inverso_idx ON reporte_animal(animal_codigo);
CREATE INDEX solicitud_animal_inverso_idx ON solicitud_animal(animal_codigo);
CREATE INDEX diagnostico_revision_catalogo_idx ON diagnostico_revision(diagnostico_id);

COMMIT;
