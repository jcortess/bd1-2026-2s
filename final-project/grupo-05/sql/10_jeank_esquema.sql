-- Modelo fisico y restricciones de integridad
-- ============================================================

-- 1. INDICACION

CREATE TABLE indicacion (
    id_indicacion bigint GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY CHECK (id_indicacion > 0),

    evaluacion_id bigint NOT NULL,

    tipo_evaluacion text NOT NULL
        DEFAULT 'REVISION_VETERINARIA'
        CHECK (tipo_evaluacion = 'REVISION_VETERINARIA'),

    tipo_indicacion text NOT NULL CHECK (
        tipo_indicacion IN (
            'TRATAMIENTO',
            'MEDICAMENTO',
            'VACUNA',
            'PROCEDIMIENTO',
            'CONTROL_POSTERIOR'
        )
    ),

    descripcion texto_no_vacio NOT NULL,

    estado_indicacion texto_no_vacio,

    indicacion_sustituida_id bigint
        REFERENCES indicacion(id_indicacion),

    CONSTRAINT indicacion_contexto_uq
        UNIQUE (id_indicacion, evaluacion_id),

    CONSTRAINT indicacion_revision_fk
        FOREIGN KEY (evaluacion_id, tipo_evaluacion)
        REFERENCES evaluacion_salud (
            id_evaluacion,
            tipo_evaluacion
        ),

    CONSTRAINT indicacion_no_autosustitucion
        CHECK (indicacion_sustituida_id <> id_indicacion)
);


-- 2. INDICACION_DIAGNOSTICO

CREATE TABLE indicacion_diagnostico (
    indicacion_id bigint NOT NULL,

    evaluacion_id bigint NOT NULL,

    diagnostico_id bigint NOT NULL,

    PRIMARY KEY (indicacion_id, diagnostico_id),

    CONSTRAINT indicacion_diagnostico_contexto_fk
        FOREIGN KEY (indicacion_id, evaluacion_id)
        REFERENCES indicacion (
            id_indicacion,
            evaluacion_id
        ),

    CONSTRAINT indicacion_diagnostico_revision_fk
        FOREIGN KEY (evaluacion_id, diagnostico_id)
        REFERENCES diagnostico_revision (
            evaluacion_id,
            diagnostico_id
        )
);


-- 3. APLICACION_INDICACION

CREATE TABLE aplicacion_indicacion (
    id_aplicacion bigint GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY CHECK (id_aplicacion > 0),

    indicacion_id bigint NOT NULL
        REFERENCES indicacion(id_indicacion),

    fecha_planificada instante NOT NULL,

    fecha_real instante,

    responsable_id bigint
        REFERENCES persona(id_persona),

    observaciones texto_no_vacio,

    CONSTRAINT aplicacion_realizada_chk CHECK (
        fecha_real IS NULL OR (
            responsable_id IS NOT NULL
            AND observaciones IS NOT NULL
        )
    )
);


-- INDICES DEL BLOQUE CLINICO

CREATE INDEX indicacion_evaluacion_idx
    ON indicacion(evaluacion_id);

CREATE INDEX indicacion_sustituida_idx
    ON indicacion(indicacion_sustituida_id);

CREATE INDEX indicacion_diagnostico_revision_idx
    ON indicacion_diagnostico(evaluacion_id, diagnostico_id);

CREATE INDEX aplicacion_indicacion_idx
    ON aplicacion_indicacion(indicacion_id);

-- ============================================================
-- BLOQUE DE RESERVAS, ADOPCIONES Y RESULTADOS
-- ============================================================

-- 4. RESERVA

CREATE TABLE reserva (
    id_reserva bigint GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY CHECK (id_reserva > 0),

    clave_operacion uuid NOT NULL UNIQUE,

    solicitud_id bigint NOT NULL,

    animal_codigo texto_no_vacio NOT NULL,

    ingreso_id bigint NOT NULL,

    compatibilidad_id bigint NOT NULL,

    fecha_reserva instante NOT NULL,

    fecha_fin_reserva instante,

    responsable_id bigint NOT NULL
        REFERENCES persona(id_persona),

    CONSTRAINT reserva_solicitud_animal_fk
        FOREIGN KEY (solicitud_id, animal_codigo)
        REFERENCES solicitud_animal (
            solicitud_id, animal_codigo
        ),

    CONSTRAINT reserva_ingreso_animal_fk
        FOREIGN KEY (ingreso_id, animal_codigo)
        REFERENCES ingreso (
            id_ingreso, animal_codigo
        ),

    CONSTRAINT reserva_compatibilidad_fk
        FOREIGN KEY (
            compatibilidad_id,
            solicitud_id,
            animal_codigo,
            ingreso_id
        )
        REFERENCES compatibilidad_animal_hogar (
            id_compatibilidad,
            solicitud_id,
            animal_codigo,
            ingreso_id
        ),

    CONSTRAINT reserva_contexto_uq
        UNIQUE (
            id_reserva,
            solicitud_id,
            animal_codigo,
            ingreso_id
        ),

    CONSTRAINT reserva_periodo_chk
        CHECK (
            fecha_fin_reserva IS NULL
            OR fecha_fin_reserva >= fecha_reserva
        )
);

CREATE UNIQUE INDEX reserva_animal_vigente_uq
    ON reserva(animal_codigo)
    WHERE fecha_fin_reserva IS NULL;

CREATE INDEX reserva_solicitud_idx
    ON reserva(solicitud_id, animal_codigo);

CREATE INDEX reserva_ingreso_idx
    ON reserva(ingreso_id);


-- 5. ADOPCION

CREATE TABLE adopcion (
    id_adopcion bigint GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY CHECK (id_adopcion > 0),

    clave_operacion uuid NOT NULL UNIQUE,

    reserva_id bigint NOT NULL UNIQUE,

    solicitud_id bigint NOT NULL,

    animal_codigo texto_no_vacio NOT NULL,

    ingreso_id bigint NOT NULL UNIQUE,

    compatibilidad_id bigint NOT NULL,

    fecha_entrega instante NOT NULL,

    condiciones_aceptadas texto_no_vacio NOT NULL,

    responsable_entrega_id bigint NOT NULL
        REFERENCES persona(id_persona),

    tipo_finalizacion text CHECK (
        tipo_finalizacion IN (
            'SATISFACTORIA',
            'DEVOLUCION_VOLUNTARIA',
            'RECUPERACION_POR_INCUMPLIMIENTO',
            'PERDIDA_CONTACTO'
        )
    ),

    fecha_finalizacion instante,

    CONSTRAINT adopcion_animal_uq
        UNIQUE (id_adopcion, animal_codigo),

    CONSTRAINT adopcion_ingreso_animal_fk
        FOREIGN KEY (ingreso_id, animal_codigo)
        REFERENCES ingreso (
            id_ingreso, animal_codigo
        ),

    CONSTRAINT adopcion_solicitud_animal_fk
        FOREIGN KEY (solicitud_id, animal_codigo)
        REFERENCES solicitud_animal (
            solicitud_id, animal_codigo
        ),

    CONSTRAINT adopcion_reserva_contexto_fk
        FOREIGN KEY (
            reserva_id,
            solicitud_id,
            animal_codigo,
            ingreso_id
        )
        REFERENCES reserva (
            id_reserva,
            solicitud_id,
            animal_codigo,
            ingreso_id
        ),

    CONSTRAINT adopcion_compatibilidad_fk
        FOREIGN KEY (
            compatibilidad_id,
            solicitud_id,
            animal_codigo,
            ingreso_id
        )
        REFERENCES compatibilidad_animal_hogar (
            id_compatibilidad,
            solicitud_id,
            animal_codigo,
            ingreso_id
        ),

    CONSTRAINT adopcion_finalizacion_par_chk
        CHECK (
            (tipo_finalizacion IS NULL)
            =
            (fecha_finalizacion IS NULL)
        ),

    CONSTRAINT adopcion_finalizacion_fecha_chk
        CHECK (
            fecha_finalizacion IS NULL
            OR fecha_finalizacion >= fecha_entrega
        )
);

CREATE INDEX adopcion_animal_idx
    ON adopcion(animal_codigo);

CREATE INDEX adopcion_solicitud_idx
    ON adopcion(solicitud_id, animal_codigo);


-- 6. ADOPCION_RESPONSABLE

CREATE TABLE adopcion_responsable (
    adopcion_id bigint NOT NULL
        REFERENCES adopcion(id_adopcion),

    persona_id bigint NOT NULL
        REFERENCES persona(id_persona),

    PRIMARY KEY (adopcion_id, persona_id)
);

CREATE INDEX adopcion_responsable_persona_idx
    ON adopcion_responsable(persona_id);


-- 7. SEGUIMIENTO_ADOPCION

CREATE TABLE seguimiento_adopcion (
    id_seguimiento bigint GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY CHECK (id_seguimiento > 0),

    adopcion_id bigint NOT NULL
        REFERENCES adopcion(id_adopcion),

    fecha_prevista instante NOT NULL,

    fecha_efectiva instante,

    responsable_id bigint NOT NULL
        REFERENCES persona(id_persona),

    medio text NOT NULL CHECK (
        medio IN (
            'LLAMADA',
            'MENSAJE',
            'VISITA',
            'REVISION_VETERINARIA'
        )
    ),

    resultado texto_no_vacio,

    acuerdo texto_no_vacio,

    estado_seguimiento text NOT NULL CHECK (
        estado_seguimiento IN (
            'PENDIENTE',
            'REALIZADO',
            'REPROGRAMADO',
            'NO_REALIZADO'
        )
    ),

    seguimiento_origen_id bigint,

    CONSTRAINT seguimiento_contexto_uq
        UNIQUE (id_seguimiento, adopcion_id),

    CONSTRAINT seguimiento_origen_fk
        FOREIGN KEY (
            seguimiento_origen_id,
            adopcion_id
        )
        REFERENCES seguimiento_adopcion (
            id_seguimiento,
            adopcion_id
        ),

    CONSTRAINT seguimiento_no_autorreferencia_chk
        CHECK (
            seguimiento_origen_id <> id_seguimiento
        ),

    CONSTRAINT seguimiento_realizado_chk
        CHECK (
            (
                estado_seguimiento = 'REALIZADO'
                AND fecha_efectiva IS NOT NULL
                AND resultado IS NOT NULL
            )
            OR
            (
                estado_seguimiento <> 'REALIZADO'
                AND fecha_efectiva IS NULL
            )
        )
);

CREATE INDEX seguimiento_adopcion_idx
    ON seguimiento_adopcion(adopcion_id);

CREATE INDEX seguimiento_origen_idx
    ON seguimiento_adopcion(seguimiento_origen_id);


-- 8. RESTRICCION_PERSONA

CREATE TABLE restriccion_persona (
    id_restriccion bigint GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY CHECK (id_restriccion > 0),

    persona_afectada_id bigint NOT NULL
        REFERENCES persona(id_persona),

    motivo texto_no_vacio NOT NULL,

    fecha_inicio instante NOT NULL,

    fecha_fin instante,

    responsable_decision_id bigint NOT NULL
        REFERENCES persona(id_persona),

    CONSTRAINT restriccion_periodo_chk
        CHECK (
            fecha_fin IS NULL
            OR fecha_fin >= fecha_inicio
        )
);

CREATE INDEX restriccion_persona_vigencia_idx
    ON restriccion_persona (
        persona_afectada_id,
        fecha_inicio,
        fecha_fin
    );


-- 9. RESULTADO_ETAPA

CREATE TABLE resultado_etapa (
    id_resultado bigint GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY CHECK (id_resultado > 0),

    ingreso_id bigint NOT NULL UNIQUE
        REFERENCES ingreso(id_ingreso),

    tipo_resultado text NOT NULL CHECK (
        tipo_resultado IN (
            'REUNIFICACION',
            'TRASLADO',
            'CUIDADO_PROLONGADO',
            'FALLECIMIENTO'
        )
    ),

    fecha instante NOT NULL,

    circunstancias texto_no_vacio NOT NULL,

    responsable_id bigint NOT NULL
        REFERENCES persona(id_persona),

    organizacion_destino_id bigint
        REFERENCES organizacion_externa(id_organizacion),

    condiciones_traslado texto_no_vacio,

    CONSTRAINT resultado_traslado_chk
        CHECK (
            tipo_resultado <> 'TRASLADO'
            OR (
                organizacion_destino_id IS NOT NULL
                AND condiciones_traslado IS NOT NULL
            )
        )
);

CREATE INDEX resultado_organizacion_idx
    ON resultado_etapa(organizacion_destino_id);


-- ============================================================
-- FIN DEL MODELO FISICO 
-- ============================================================

COMMIT;