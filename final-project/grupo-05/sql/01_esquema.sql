\set ON_ERROR_STOP on
BEGIN;

CREATE SCHEMA huellas;
CREATE EXTENSION IF NOT EXISTS btree_gist WITH SCHEMA public;
SET LOCAL search_path = huellas, pg_catalog, public;

DO $$
BEGIN
    IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'huellas_g05_operador') THEN
        CREATE ROLE huellas_g05_operador NOLOGIN;
    END IF;
END
$$;

REVOKE ALL ON SCHEMA huellas FROM PUBLIC;
GRANT USAGE ON SCHEMA huellas TO huellas_g05_operador;

CREATE DOMAIN texto_no_vacio AS text CHECK (VALUE ~ '[^[:space:]]');
CREATE DOMAIN especie_animal AS text CHECK (VALUE ~ '^[A-Z][A-Z0-9_]*$');
CREATE DOMAIN instante AS timestamptz CHECK (isfinite(VALUE));

CREATE TABLE persona (
    id_persona bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id_persona > 0),
    nombre_identificacion texto_no_vacio
);

CREATE TABLE medio_contacto (
    id_medio bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id_medio > 0),
    persona_id bigint NOT NULL REFERENCES persona,
    tipo_medio texto_no_vacio NOT NULL,
    valor texto_no_vacio NOT NULL
);

CREATE TABLE participacion (
    id_participacion bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id_participacion > 0),
    persona_id bigint NOT NULL REFERENCES persona,
    tipo_participacion text NOT NULL CHECK (tipo_participacion IN
        ('PERSONAL_PERMANENTE', 'VOLUNTARIO', 'VETERINARIO', 'HOGAR_TEMPORAL', 'SOLICITANTE', 'ADOPTANTE')),
    fecha_inicio instante NOT NULL,
    fecha_fin instante,
    requisitos texto_no_vacio,
    estado_aprobacion_registro text CHECK (estado_aprobacion_registro IN
        ('PENDIENTE', 'APROBADO', 'REGISTRADO', 'RECHAZADO')),
    fecha_aprobacion_registro instante,
    CONSTRAINT participacion_periodo CHECK (fecha_fin IS NULL OR fecha_fin > fecha_inicio),
    CONSTRAINT participacion_aprobacion CHECK (
        (tipo_participacion <> 'HOGAR_TEMPORAL' OR
            (estado_aprobacion_registro IS NOT NULL AND estado_aprobacion_registro <> 'REGISTRADO'))
        AND (fecha_aprobacion_registro IS NOT NULL) =
            coalesce(estado_aprobacion_registro IN ('APROBADO', 'REGISTRADO'), false)
        AND (fecha_fin IS NULL OR fecha_aprobacion_registro < fecha_fin)
    )
);

CREATE TABLE animal (
    codigo_interno texto_no_vacio PRIMARY KEY,
    nombre texto_no_vacio,
    especie especie_animal NOT NULL,
    sexo text CHECK (sexo IN ('HEMBRA', 'MACHO')),
    color texto_no_vacio,
    tamano_aproximado text CHECK (tamano_aproximado IN ('PEQUENO', 'MEDIANO', 'GRANDE')),
    edad_estimada integer CHECK (edad_estimada >= 0),
    senas_particulares texto_no_vacio,
    numero_microchip texto_no_vacio UNIQUE CHECK (numero_microchip = btrim(numero_microchip))
);

CREATE TABLE organizacion_externa (
    id_organizacion bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id_organizacion > 0),
    nombre_organizacion texto_no_vacio NOT NULL
);

CREATE TABLE ingreso (
    id_ingreso bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id_ingreso > 0),
    animal_codigo texto_no_vacio NOT NULL REFERENCES animal,
    fecha_ingreso instante NOT NULL,
    lugar_ingreso texto_no_vacio NOT NULL,
    condicion_general texto_no_vacio NOT NULL,
    circunstancia_ingreso text NOT NULL CHECK (circunstancia_ingreso IN
        ('RESCATE', 'ENTREGA_VOLUNTARIA', 'TRASLADO', 'DEVOLUCION', 'RECUPERACION', 'OTRA')),
    detalle_circunstancia texto_no_vacio,
    propietario_anterior_id bigint REFERENCES persona,
    organizacion_origen_id bigint REFERENCES organizacion_externa,
    adopcion_origen_id bigint UNIQUE CHECK (adopcion_origen_id > 0),
    receptor_devolucion_id bigint REFERENCES persona,
    fecha_cierre instante,
    CONSTRAINT ingreso_animal_uq UNIQUE (id_ingreso, animal_codigo),
    CONSTRAINT ingreso_periodo CHECK (fecha_cierre IS NULL OR fecha_cierre > fecha_ingreso),
    CONSTRAINT ingreso_etapas_no_solapan EXCLUDE USING gist (
        (animal_codigo::text) WITH =, tstzrange(fecha_ingreso, fecha_cierre, '[)') WITH &&
    ),
    CONSTRAINT ingreso_detalle CHECK (
        circunstancia_ingreso NOT IN ('DEVOLUCION', 'RECUPERACION', 'OTRA') OR detalle_circunstancia IS NOT NULL
    ),
    CONSTRAINT ingreso_organizacion CHECK (
        (circunstancia_ingreso = 'TRASLADO') = (organizacion_origen_id IS NOT NULL)
    ),
    CONSTRAINT ingreso_receptor CHECK (
        (circunstancia_ingreso IN ('DEVOLUCION', 'RECUPERACION')) = (receptor_devolucion_id IS NOT NULL)
    ),
    CONSTRAINT ingreso_origen_adopcion CHECK (
        (circunstancia_ingreso IN ('DEVOLUCION', 'RECUPERACION')) = (adopcion_origen_id IS NOT NULL)
    ),
    CONSTRAINT zz_ingreso_adopcion_pendiente CHECK (adopcion_origen_id IS NULL)
);

CREATE TABLE ubicacion (
    id_ubicacion bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id_ubicacion > 0),
    tipo_ubicacion text NOT NULL CHECK (tipo_ubicacion IN ('AREA_INTERNA', 'HOGAR_TEMPORAL', 'ATENCION_EXTERNA')),
    nombre_descripcion texto_no_vacio NOT NULL,
    capacidad integer CHECK (capacidad > 0),
    condicion_admitida texto_no_vacio,
    disponibilidad_desde instante,
    disponibilidad_hasta instante,
    persona_oferente_id bigint REFERENCES persona,
    codigo_hogar texto_no_vacio,
    CONSTRAINT ubicacion_por_tipo CHECK (
        (tipo_ubicacion <> 'ATENCION_EXTERNA') = (capacidad IS NOT NULL)
        AND (tipo_ubicacion = 'AREA_INTERNA') = (condicion_admitida IS NOT NULL)
        AND (tipo_ubicacion = 'HOGAR_TEMPORAL') = (disponibilidad_desde IS NOT NULL)
        AND (tipo_ubicacion = 'HOGAR_TEMPORAL') = (disponibilidad_hasta IS NOT NULL)
        AND (tipo_ubicacion = 'HOGAR_TEMPORAL') = (persona_oferente_id IS NOT NULL)
        AND (tipo_ubicacion = 'HOGAR_TEMPORAL') = (codigo_hogar IS NOT NULL)
        AND (tipo_ubicacion <> 'HOGAR_TEMPORAL' OR disponibilidad_desde < disponibilidad_hasta)
    ),
    CONSTRAINT ubicacion_ofertas_no_solapan EXCLUDE USING gist (
        (codigo_hogar::text) WITH =, tstzrange(disponibilidad_desde, disponibilidad_hasta, '[)') WITH &&
    ) WHERE (tipo_ubicacion = 'HOGAR_TEMPORAL')
);

CREATE TABLE ubicacion_especie_aceptada (
    ubicacion_id bigint NOT NULL REFERENCES ubicacion,
    especie especie_animal NOT NULL,
    PRIMARY KEY (ubicacion_id, especie)
);

CREATE TABLE estancia (
    id_estancia bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id_estancia > 0),
    animal_codigo texto_no_vacio NOT NULL,
    ingreso_id bigint NOT NULL,
    ubicacion_id bigint NOT NULL REFERENCES ubicacion,
    fecha_inicio_real instante NOT NULL,
    fecha_fin_real instante,
    fecha_inicio_prevista instante,
    fecha_fin_prevista instante,
    condicion_especial texto_no_vacio,
    condicion_alojamiento texto_no_vacio,
    actor_entrada_id bigint NOT NULL REFERENCES persona,
    actor_salida_id bigint REFERENCES persona,
    aprobacion_hogar_id bigint REFERENCES participacion,
    valoracion_sanitaria texto_no_vacio,
    CONSTRAINT estancia_ingreso_animal_fk FOREIGN KEY (ingreso_id, animal_codigo)
        REFERENCES ingreso (id_ingreso, animal_codigo),
    CONSTRAINT estancia_no_solapa EXCLUDE USING gist (
        (animal_codigo::text) WITH =, tstzrange(fecha_inicio_real, fecha_fin_real, '[)') WITH &&
    ),
    CONSTRAINT estancia_periodo_real CHECK (fecha_fin_real IS NULL OR fecha_fin_real > fecha_inicio_real),
    CONSTRAINT estancia_cierre CHECK ((fecha_fin_real IS NULL) = (actor_salida_id IS NULL)),
    CONSTRAINT estancia_periodo_previsto CHECK (
        (fecha_inicio_prevista IS NULL) = (fecha_fin_prevista IS NULL)
        AND (fecha_fin_prevista IS NULL OR fecha_fin_prevista > fecha_inicio_prevista)
    )
);

CREATE INDEX estancia_abierta_animal_idx ON estancia (animal_codigo) WHERE fecha_fin_real IS NULL;
CREATE INDEX estancia_ubicacion_inicio_idx ON estancia (ubicacion_id, fecha_inicio_real);
CREATE INDEX estancia_ingreso_idx ON estancia (ingreso_id);
CREATE INDEX estancia_aprobacion_idx ON estancia (aprobacion_hogar_id) WHERE aprobacion_hogar_id IS NOT NULL;
CREATE INDEX participacion_oferente_idx ON participacion (persona_id, fecha_aprobacion_registro)
    WHERE tipo_participacion = 'HOGAR_TEMPORAL' AND estado_aprobacion_registro = 'APROBADO';

COMMIT;
